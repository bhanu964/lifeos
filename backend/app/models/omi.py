from typing import Any, Dict, List, Optional, Union
from pydantic import BaseModel, ConfigDict, Field


class TranscriptSegment(BaseModel):
    """
    Individual transcript segment from Omi.
    Supports standard speaker diarization, timing and user attribution.
    """
    model_config = ConfigDict(extra="ignore")

    text: str = Field(default="", description="Transcribed spoken chunk")
    speaker: Optional[str] = Field(default=None, description="Diarization speaker label, e.g., SPEAKER_00")
    speakerId: Optional[int] = Field(default=None, description="Speaker numeric identifier")
    speaker_name: Optional[str] = Field(default=None, description="Resolved speaker name if available")
    is_user: Optional[bool] = Field(default=False, description="Flag indicating if the wearer was the speaker")
    start: Optional[float] = Field(default=None, description="Start time offset in seconds")
    end: Optional[float] = Field(default=None, description="End time offset in seconds")


class OmiActionItem(BaseModel):
    model_config = ConfigDict(extra="ignore")
    description: str
    completed: bool = False


class OmiStructured(BaseModel):
    """Structured memory details generated by Omi."""
    model_config = ConfigDict(extra="ignore")

    title: Optional[str] = None
    overview: Optional[str] = None
    emoji: Optional[str] = None
    category: Optional[str] = None
    action_items: Optional[List[Any]] = Field(default_factory=list)
    events: Optional[List[Any]] = Field(default_factory=list)


class ConversationPayload(BaseModel):
    """
    Payload for POST /omi/conversation.
    Received when an Omi conversation/session finishes and generates a completed memory.
    """
    model_config = ConfigDict(extra="ignore")

    id: Optional[str] = Field(default=None, description="Memory ID generated by Omi")
    uid: Optional[str] = Field(default=None, description="User identifier (if provided in body)")
    created_at: Optional[str] = None
    started_at: Optional[str] = None
    finished_at: Optional[str] = None
    language: Optional[str] = "en"
    source: Optional[str] = "omi"
    transcript_segments: Optional[List[TranscriptSegment]] = Field(default_factory=list)
    segments: Optional[List[TranscriptSegment]] = Field(default=None, description="Fallback field for segments")
    structured: Optional[OmiStructured] = None
    discarded: Optional[bool] = False
    session_id: Optional[str] = None


class RealtimePayload(BaseModel):
    """
    Payload for POST /omi/realtime.
    Sent incrementally during active listening.
    """
    model_config = ConfigDict(extra="ignore")

    session_id: Optional[str] = None
    segments: List[TranscriptSegment] = Field(default_factory=list)


class OmiWebhookResponse(BaseModel):
    """Webhook response returned immediately to Omi."""
    status: str
    message: str
    processed_count: int
    session_id: Optional[str] = None
    memory_id: Optional[str] = None
    workflow_id: Optional[str] = None
